def _select_fp8_q4(requests, hkv, group, sm100, page):
    measured = (requests in (1, 2)
                or 4 <= requests <= 64 and requests % 2 == 0
                or 68 <= requests <= 256 and requests % 4 == 0)
    if measured:
        for low, high, pages, br, splits in _FP8_Q4_INTERVALS.get((sm100, group, hkv), ()):
            if low <= requests <= high and page in pages:
                return br, splits
    return None
